export const TZ = 'Europe/Amsterdam';
const toMin = (t) => {
  const [h, m] = t.split(':').map(Number);
  return h * 60 + m;
};
const pad = (n) => String(n).padStart(2, '0');
export const todayIso = (d = new Date()) => new Intl.DateTimeFormat('en-CA', { timeZone: TZ }).format(d);
export const nowMin = () => {
  const [h, m] = new Intl.DateTimeFormat('en-GB', { timeZone: TZ, hour: '2-digit', minute: '2-digit', hourCycle: 'h23' })
    .format(new Date())
    .split(':')
    .map(Number);
  return h * 60 + m;
};
export const dayOf = (iso) => new Date(`${iso}T12:00:00Z`).getUTCDay();
export const addDays = (iso, n) => {
  const d = new Date(`${iso}T12:00:00Z`);
  d.setUTCDate(d.getUTCDate() + n);
  return d.toISOString().slice(0, 10);
};
export const longDate = (iso, opts = {}) =>
  new Intl.DateTimeFormat('nl-NL', { weekday: 'long', day: 'numeric', month: 'long', timeZone: 'UTC', ...opts }).format(
    new Date(`${iso}T12:00:00Z`),
  );
export const shortDate = (iso) =>
  new Intl.DateTimeFormat('nl-NL', { weekday: 'short', day: 'numeric', month: 'short', timeZone: 'UTC' }).format(
    new Date(`${iso}T12:00:00Z`),
  );
export const stamp = (ts) =>
  new Intl.DateTimeFormat('nl-NL', { day: 'numeric', month: 'short', hour: '2-digit', minute: '2-digit', timeZone: TZ }).format(
    new Date(ts),
  );

export const hoursFor = (iso) => SITE.openingHours.find((d) => d.index === dayOf(iso));

export function openStatus() {
  const iso = todayIso();
  const h = hoursFor(iso);
  const now = nowMin();
  const kitchen = toMin(SITE.reservation.kitchenCloses);
  if (h?.status === 'open') {
    if (now < toMin(h.opens)) return { open: false, text: `Vandaag open vanaf ${h.opens}` };
    if (now < kitchen) return { open: true, text: `Nu open, keuken tot ${SITE.reservation.kitchenCloses}` };
    if (now < toMin(h.closes)) return { open: true, text: `Open tot ${h.closes}, keuken gesloten` };
  }
  for (let i = 1; i <= 7; i++) {
    const next = addDays(iso, i);
    const nh = hoursFor(next);
    if (nh?.status === 'open') {
      const when = i === 1 ? 'morgen' : longDate(next, { month: undefined, day: undefined });
      return { open: false, text: `Gesloten, ${when} open vanaf ${nh.opens}` };
    }
  }
  return { open: false, text: 'Gesloten' };
}

export const isTapasDay = (iso = todayIso()) => SITE.tapasDay.dayIndexes.includes(dayOf(iso));

export function slotsFor(iso, blocked = []) {
  const h = hoursFor(iso);
  if (!h || h.status !== 'open' || blocked.includes(iso)) return [];
  const last = toMin(SITE.reservation.kitchenCloses) - SITE.reservation.lastSlotOffset;
  const from = Math.max(toMin(h.opens), iso === todayIso() ? nowMin() + 60 : 0);
  const out = [];
  for (let t = toMin(h.opens); t <= last; t += SITE.reservation.slotStep)
    if (t >= from) out.push(`${pad(Math.floor(t / 60))}:${pad(t % 60)}`);
  return out;
}

export function greeting() {
  const m = nowMin();
  if (m < 12 * 60) return 'Buenos días';
  if (m < 18 * 60) return 'Buenas tardes';
  return 'Buenas noches';
}

export const reduceMotion = () => window.matchMedia('(prefers-reduced-motion: reduce)').matches;
export const gsapOk = () => typeof window.gsap !== 'undefined' && !reduceMotion();

let toastTimer;
export function toast(message, tone = 'ok') {
  let region = document.querySelector('.toast-region');
  if (!region) {
    region = document.createElement('div');
    region.className = 'toast-region';
    region.setAttribute('role', 'status');
    region.setAttribute('aria-live', 'polite');
    document.body.append(region);
  }
  region.innerHTML = `<div class="toast" data-tone="${tone}">${esc(message)}</div>`;
  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => {
    region.innerHTML = '';
  }, 4200);
}

export function countUp(el, from, to) {
  if (!el) return;
  if (!gsapOk() || from === to) {
    el.textContent = String(to);
    return;
  }
  const o = { v: from };
  window.gsap.to(o, {
    v: to,
    duration: 0.9,
    ease: 'power2.out',
    onUpdate: () => {
      el.textContent = String(Math.round(o.v));
    },
  });
}

